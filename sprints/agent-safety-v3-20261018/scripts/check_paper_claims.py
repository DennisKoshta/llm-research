"""Mechanical checks for the paper in paper/.

  PYTHONPATH=src .venv/bin/python scripts/check_paper_claims.py [--skip-safety]

1. CLAIMS     every claim in paper/paper.claims.json re-evaluates (formula over records/*.json) to its stored value.
2. FRESHNESS  re-running the generator into a temp dir reproduces paper/generated/facts.tex and paper/tables/*.tex byte for
              byte, so every table cell and \\fact value is the current record value.
3. NO BARE NUMBERS  the hand-written .tex (main.tex, sections/*.tex) contains no digit outside \\fact{...}, references,
              citations, file names and an allowlist of identifiers (Exp~1.1, Phase~1, layer~48, Qwen3.8-27B, $r{=}32$, ...).
4. TEXT SAFETY  no 50-character window of any paper .tex file occurs in any string of data/**/*.json(l) (authored scenarios,
              memos, notes, worlds, request prompts, SFT targets), except windows inside the three neutral calibration
              sentences stored in records/calibration_history.json. Prints counts and file names only, never matched text.
Exit status is non-zero if any check fails.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import pathlib
import re
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
W = 50


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def check_claims() -> int:
    crc = load("check_report_claims", ROOT / "scripts" / "check_report_claims.py")
    records = crc.load_records()
    claims = json.loads((PAPER / "paper.claims.json").read_text())
    bad = 0
    for c in claims:
        ok, msg = crc.check_claim(c, records)
        if not ok:
            bad += 1
            print(f"[FAIL] claim {c['id']}: {msg}")
    print(f"[claims] {len(claims) - bad} OK, {bad} failing")
    return bad


def check_freshness() -> int:
    build = load("build_paper_artifacts", ROOT / "scripts" / "build_paper_artifacts.py")
    with tempfile.TemporaryDirectory() as td:
        tmp = pathlib.Path(td)
        (tmp / "tables").mkdir()
        (tmp / "generated").mkdir()
        build.PAPER = tmp
        build.build_facts()
        build.build_tables()
        lines = ["% generated by scripts/build_paper_artifacts.py from records/*.json -- do not edit"]
        lines += [f"\\FACT{{{k}}}{{{v}}}" for k, v in sorted(build.FACTS.items())]
        fresh = {"generated/facts.tex": "\n".join(lines) + "\n"}
        fresh.update({f"tables/{p.name}": p.read_text() for p in (tmp / "tables").glob("*.tex")})
    stale = [k for k, v in fresh.items() if not (PAPER / k).exists() or (PAPER / k).read_text() != v]
    extra = [str(p.relative_to(PAPER)) for p in (PAPER / "tables").glob("*.tex") if f"tables/{p.name}" not in fresh]
    for k in stale + extra:
        print(f"[FAIL] stale or unexpected generated file: {k}")
    print(f"[freshness] {len(fresh) - len(stale)}/{len(fresh)} generated files reproduce exactly; {len(extra)} unexpected")
    return len(stale) + len(extra)


ALLOW = [
    r"\\(fact|ref|label|cite[pt]?|input|includegraphics|bibliography|bibliographystyle)(\[[^\]]*\])?\{[^}]*\}",
    r"\\FACT\{[^}]*\}\{[^}]*\}",
    r"Exp(eriments?)?~?\s?\d\.\d(?:,\s*\d\.\d)*(?:\s*(?:and|--|/)\s*\d\.\d)*",
    r"Exp~?\d\.\d", r"\b\d\.\d(?= and\b| \(|,)",                 # experiment lists such as "2.3, 2.1 and 2.2"
    r"Phase~?\s?\d", r"Run~?\d", r"(?i:layer)[~-]?\d+", r"#\d", r"95\\%", r"PCA-10[1-3](?:/10[1-3])*", r"\d+-bit", r"Qwen\d(\.\d)?-[\w-]+", r"Llama-\d\.\d-\d+B",
    r"\$r\{=\}\d+\$", r"\bv\d\b", r"\b(A|B|C|D|P|R|F)\d(?:\.\d)?[ab]?\b", r"B\$'\$", r"\b(P1|C)\d", r"\bA[0-2]\b",
    r"\\[a-zA-Z]+\[[^\]]*\]", r"\[\d+pt\]", r"\d+(\.\d+)?(in|pt|em)\b", r"\{\d\.\d+\\linewidth\}", r"0\.\d+\\linewidth",
    r"agent-safety-v3-\d+", r"\\texttt\{[^}]*\}", r"BF16|FP8", r"blue!\d+!black", r"\b10pt\b", r"October 2026",
    r"\\sectionmark|\\\\\[\d+pt\]", r"\\newcommand\{\\[A-Za-z]+\}\[\d\]",
]
ALLOW_RE = re.compile("|".join(f"(?:{a})" for a in ALLOW))


def check_bare_numbers() -> int:
    files = [PAPER / "main.tex"] + sorted((PAPER / "sections").glob("*.tex"))
    bad = 0
    for f in files:
        for i, line in enumerate(f.read_text().splitlines(), 1):
            s = re.sub(r"(?<!\\)%.*", "", line)            # comments
            s = ALLOW_RE.sub(" ", s)
            for m in re.finditer(r"\d+(?:[.,]\d+)?", s):
                bad += 1
                print(f"[FAIL] bare number '{m.group(0)}' in {f.relative_to(PAPER)}:{i}")
    print(f"[bare-numbers] {bad} hand-typed numbers in {len(files)} hand-written files")
    return bad


def leaves(o):
    if isinstance(o, str):
        yield o
    elif isinstance(o, dict):
        for v in o.values():
            yield from leaves(v)
    elif isinstance(o, list):
        for v in o:
            yield from leaves(v)


def norm(s: str) -> str:
    return " ".join(s.lower().split())


def check_text_safety() -> int:
    targets = sorted(PAPER.rglob("*.tex")) + [PAPER / "paper.claims.json"]
    allowed = [norm(v["system_prompt_sentence"]) for v in
               json.loads((ROOT / "records" / "calibration_history.json").read_text())["versions"].values()]
    windows = {}
    for t in targets:
        txt = norm(t.read_text(errors="replace"))
        for i in range(max(0, len(txt) - W + 1)):
            w = txt[i:i + W]
            if not any(w in a for a in allowed):
                windows.setdefault(w, set()).add(str(t.relative_to(PAPER)))
    hits: dict[str, int] = {}
    n_strings = 0
    for p in sorted((ROOT / "data").rglob("*")):
        if p.suffix not in (".json", ".jsonl"):
            continue
        with open(p, errors="replace") as fh:
            rows = fh if p.suffix == ".jsonl" else [fh.read()]
            for line in rows:
                if not line.strip():
                    continue
                try:
                    obj = json.loads(line)
                except Exception:
                    continue
                for s in leaves(obj):
                    if len(s) < W:
                        continue
                    n_strings += 1
                    t = norm(s)
                    for i in range(len(t) - W + 1):
                        tf = windows.get(t[i:i + W])
                        if tf:
                            for name in tf:
                                hits[name] = hits.get(name, 0) + 1
                            break
    for name, n in sorted(hits.items()):
        print(f"[FAIL] {name}: {n} data strings share a {W}-character window with this file (text not printed)")
    print(f"[text-safety] scanned {len(targets)} paper files against {n_strings} data strings; {len(hits)} files with overlap")
    return len(hits)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--skip-safety", action="store_true")
    a = ap.parse_args(argv)
    fails = check_claims() + check_freshness() + check_bare_numbers()
    if not a.skip_safety:
        fails += check_text_safety()
    print("ALL CHECKS PASSED" if fails == 0 else f"{fails} FAILURES")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
