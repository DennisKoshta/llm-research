    outs_qwen = llm_qwen.generate(p_qwen, SamplingParams(temperature=0.0, max_tokens=48, skip_special_tokens=True))
    for m, o in zip(m_qwen, outs_qwen):
        sc = score_monitor_output(m, o.outputs[0].text)
        sc["monitor_model"] = "Qwen3.8-27B-FP8-Intact-Requant"
        all_records.append(sc)

    del llm_qwen
    gc.collect()
    torch.cuda.empty_cache()

    # 2. Cross-Family Monitor Check: Llama-3.3-70B-Instruct-FP8-dynamic
    print("Running Cross-Family Offline Monitor (Llama-3.3-70B-Instruct-FP8-dynamic)...", flush=True)
