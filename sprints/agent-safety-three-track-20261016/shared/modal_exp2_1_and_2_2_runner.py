def _strip_think(text: str) -> str:
    for tok in ("<|im_end|>", "<|endoftext|>", "<|fim_pad|>"):
        text = text.replace(tok, "")
    if "</think>" in text:
        return text.split("</think>", 1)[1].strip()
    if "<think>" in text:
        return re.sub(r"<think>.*?(?:</think>|$)", "", text, flags=re.DOTALL).strip()
    return text.strip()


